export function normalizeLocale(value) {
  return value === 'pt' ? 'pt' : 'en'
}

export function translate(locale, key, vars) {
  const lang = normalizeLocale(locale)
  let text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (_, name) =>
      vars[name] == null ? `{${name}}` : String(vars[name]),
    )
  }
  return text
}

export function sourceTypeName(type, locale) {
  const labels = SOURCE_TYPE_LABELS[type]
  if (!labels) return type
  return normalizeLocale(locale) === 'pt' ? labels.pt : labels.en
}

export function hazardName(typeId, locale) {
  const type = HAZARD_TYPES.find((h) => h.id === typeId)
  if (!type) return typeId
  return normalizeLocale(locale) === 'pt' ? type.pt : type.en
}

export function measureName(measureId, fallback, t) {
  const key = `measure.${measureId}`
  const value = t(key)
  return value === key ? fallback : value
}

export function sessionName(session, t) {
  if (!session) return t('session.fallback')
  const byId = t(`session.${session.id}`)
  if (byId !== `session.${session.id}`) return byId
  if (session.label === 'Today') return t('session.today')
  return session.label
}
